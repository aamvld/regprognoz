class HelpWindow(QDialog):
    """Окно справки со всеми разделами на одной странице."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Справка — РегПрогноз")
        self.resize(720, 600)
        self.sections = HELP_SECTIONS

        browser = QTextBrowser()
        html = "<h2>Программная система «РегПрогноз»</h2>"
        for head, body in self.sections:
            html += f"<h3>{head}</h3>{body}"
        browser.setHtml(html)

        close_btn = QPushButton("Закрыть")
        close_btn.clicked.connect(self.close)

        layout = QVBoxLayout(self)
        layout.addWidget(browser)
        layout.addWidget(close_btn)
